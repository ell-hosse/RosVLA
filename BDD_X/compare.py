#!/usr/bin/env python3
"""Write comparison_<text_field>.md from all finished runs (mean +- std over seeds).

    python compare.py
    python compare.py --text-field action
    python compare.py --tag __4f-concat         # frame setting of the image runs
"""
from __future__ import annotations

import argparse
import json

from config import ABLATIONS, HERE

LABEL = {"f1_img_state": "F1  frames + vehicle signals  (the CoVLA flow head)",
         "f2_state_only": "F2  vehicle signals only",
         "f3_img_only": "F3  frames only"}

# RAG-Driver (Yuan et al., RSS 2024), Table I, BDD-X test, in-distribution.
# B4 = BLEU-4, C = CIDEr, M = METEOR, all x100. These methods generate text;
# ours retrieves the nearest training caption.
SOTA = [("S2VT", 30.2, 179.8, 27.5, 6.3, 53.4, 11.2),
        ("S2VT++", 27.1, 157.0, 26.4, 5.8, 52.7, 10.9),
        ("SAA", 31.8, 214.8, 29.1, 7.1, 66.1, 12.2),
        ("WAA", 32.3, 215.8, 29.2, 7.3, 69.5, 12.2),
        ("ADAPT", 34.6, 247.5, 30.6, 11.4, 102.6, 15.2),
        ("DriveGPT4", 30.0, 214.0, 29.8, 9.4, 102.7, 14.6),
        ("RAG-Driver", 34.3, 260.8, 30.7, 11.1, 109.1, 14.8)]
SOTA_SRC = "https://arxiv.org/abs/2402.10828"


def f(x, nd=4):
    if x is None:
        return "-"
    if isinstance(x, dict):
        return f"{x['mean']:.{nd}f}" + (f" ± {x['std']:.{nd}f}" if x.get("n", 1) > 1 else "")
    return f"{x:.{nd}f}"


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--text-field", default="action_justification")
    ap.add_argument("--tag", default="__4f-concat",
                    help="suffix of the image runs' folder (frame setting), e.g. __1f-concat")
    args = ap.parse_args()
    tf = args.text_field

    rows = {}
    for ab in ABLATIONS:
        tag = tf + (args.tag if ab != "f2_state_only" else "")
        p = HERE / "runs" / ab / tag / "summary.json"
        if p.exists():
            rows[ab] = json.loads(p.read_text())
    if not rows:
        print("no finished runs -- train first")
        return

    L = [f"# BDD-X flow head -- text field `{tf}`", "",
         "Text target: MiniLM embedding of the caption, generated by the rectified-flow head "
         "through a PCA latent. Test = official BDD-X test videos. Mean ± std over seeds.", ""]

    for sp in ("test", "val", "train"):
        L += [f"## Embedding fidelity -- {sp}", "",
              "| model | params | cosine (generated) | best of 5 | PCA ceiling | mean baseline | "
              "kNN baseline | scaled (0 = mean, 1 = ceiling) |", "|---|---|---|---|---|---|---|---|"]
        for ab, s in rows.items():
            t = s[sp]
            bk = next(k for k in t if k.startswith("cosine_best_of_"))
            L.append(f"| {LABEL[ab]} | {s['params']:,} | {f(t['cosine_model'])} | {f(t[bk])} | "
                     f"{f(t['cosine_pca_ceiling'])} | {f(t['cosine_mean_baseline'])} | "
                     f"{f(t['cosine_knn_baseline'])} | {f(t['scaled_score'], 3)} |")
        L.append("")

    L += ["## Retrieval-decoded captions -- test", "",
          "The generated embedding is decoded to the nearest TRAINING caption. `oracle` decodes "
          "the true embedding (the ceiling of this decoder); `mean` always decodes the same "
          "caption. Action / justification BLEU-4 and CIDEr-D are x100.", "",
          "| model | action-class acc | retrieved-caption cosine | action B4 | action CIDEr | "
          "justification B4 | justification CIDEr |", "|---|---|---|---|---|---|---|"]
    ref = None
    for ab, s in rows.items():
        t = s["test"]
        ref = t
        L.append(f"| {LABEL[ab]} | {f(t['decode_action_class_accuracy'], 3)} | "
                 f"{f(t['decode_retrieved_caption_cosine'])} | {f(t['decode_action_bleu4'], 1)} | "
                 f"{f(t['decode_action_cider'], 1)} | {f(t['decode_justification_bleu4'], 1)} | "
                 f"{f(t['decode_justification_cider'], 1)} |")
    for name, key in (("_oracle: decode the true embedding_", "decode_oracle"),
                      ("_mean baseline: one caption for everything_", "decode_mean_baseline")):
        o = ref[key]
        L.append(f"| {name} | {o['action_class_accuracy']:.3f} | {o['retrieved_caption_cosine']:.4f} | "
                 f"{o['action_bleu4']:.1f} | {o['action_cider']:.1f} | {o['justification_bleu4']:.1f} | "
                 f"{o['justification_cider']:.1f} |")
    L += ["", f"Majority action class accuracy: {ref['action_class_majority_accuracy']:.3f}.", ""]

    L += ["## Published BDD-X explanation results (for context)", "",
          "| method | action B4 | action CIDEr | action METEOR | justification B4 | "
          "justification CIDEr | justification METEOR |", "|---|---|---|---|---|---|---|"]
    for n, *v in SOTA:
        L.append(f"| {n} | " + " | ".join(f"{x:.1f}" for x in v) + " |")
    L += ["", f"Source: RAG-Driver, Table I ({SOTA_SRC}). Same official test set (2,123 clips). "
          "Those models generate free text; the flow head here produces an embedding, and the "
          "caption-metric columns above come from retrieving a training caption -- so they are "
          "bounded by the `oracle` row and the comparison is indicative, not like-for-like. "
          "METEOR is not computed here.", ""]

    out = HERE / f"comparison_{tf}.md"
    out.write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L))
    print(f"\nwritten -> {out}")


if __name__ == "__main__":
    main()
